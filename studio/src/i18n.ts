const storageKey = "lvgl-studio-locale";
let locale: Locale = "en";

function detectLocale(): Locale {
  if (typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("zh")) return "zh-CN";
  return "en";
}

export function initI18n(root: ParentNode = document): void {
  let saved: string | null = null;
  try { saved = typeof localStorage === "undefined" ? null : localStorage.getItem(storageKey); } catch { /* Storage may be unavailable. */ }
  locale = saved === "zh-CN" || saved === "en" ? saved : detectLocale();
  applyI18n(root);
  for (const button of root.querySelectorAll<HTMLButtonElement>("[data-locale-choice]")) {
    button.addEventListener("click", () => setLocale(button.dataset.localeChoice as Locale));
  }
}

export function setLocale(next: Locale): void {
  locale = next;
  try { localStorage.setItem(storageKey, next); } catch { /* Storage may be unavailable. */ }
  applyI18n(document);
  document.dispatchEvent(new CustomEvent("lvgl-locale-change", { detail: next }));
}

export function getLocale(): Locale { return locale; }

export function t(key: string, values: Record<string, string | number> = {}): string {
  const value = messages[locale][key] ?? messages.en[key] ?? key;
  return typeof value === "function" ? value(values) : value;
}

export function applyI18n(root: ParentNode = document): void {
  if (root === document) document.documentElement.lang = locale === "zh-CN" ? "zh-CN" : "en";
  for (const element of root.querySelectorAll<HTMLElement>("[data-i18n]")) {
    const frame = element.dataset.i18nFrame;
    element.textContent = t(element.dataset.i18n || "", frame === undefined ? {} : { frame });
  }
  for (const element of root.querySelectorAll<HTMLElement>("[data-i18n-aria-label]")) {
    element.setAttribute("aria-label", t(element.dataset.i18nAriaLabel || ""));
  }
  for (const element of root.querySelectorAll<HTMLElement>("[data-i18n-title]")) {
    element.setAttribute("title", t(element.dataset.i18nTitle || ""));
  }
  for (const button of root.querySelectorAll<HTMLButtonElement>("[data-locale-choice]")) {
    button.setAttribute("aria-pressed", String(button.dataset.localeChoice === locale));
  }
}
